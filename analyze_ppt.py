# hex dump 前 128 字节
print("前 128 字节 hex dump:")
for i in range(0, min(128, len(data)), 16):
    chunk = data[i:i+16]
    hex_str = " ".join(f"{b:02x}" for b in chunk)
    ascii_str = "".join(chr(b) if 32 <= b < 127 else "." for b in chunk)
    print(f"  {i:04x}: {hex_str:<48s} {ascii_str}")
print()

# 查找可能的频率值 (MHz * 100 = 50000, 80000 等)
# PowerPlayTable 中频率通常以 10kHz 为单位存储
# 500 MHz = 50000 (0xC350)
# 800 MHz = 80000 (0x13880)
# 1000 MHz = 100000 (0x186A0)
print("=== 搜索频率值 (500MHz=50000, 800MHz=80000) ===")
target_freqs = {
    50000: "500 MHz",
    80000: "800 MHz",
    100000: "1000 MHz",
    163000: "1630 MHz (核心)",
    125000: "1250 MHz",
    85200: "852 MHz",
    40000: "400 MHz",
    60000: "600 MHz",
    10000: "100 MHz",
    20000: "200 MHz",
    30000: "300 MHz",
}

for target, label in target_freqs.items():
    target_bytes = struct.pack("<I", target)
    positions = []
    start = 0
    while True:
        pos = data.find(target_bytes, start)
        if pos == -1:
            break
        positions.append(pos)
        start = pos + 1
    if positions:
        print(f"  {label} (0x{target:08x}): 找到 {len(positions)} 处, 位置: {[hex(p) for p in positions]}")

print()
print("=== 搜索 16 位频率值 (10kHz 单位) ===")
for target_16, label in [(5000, "500MHz(16bit)"), (8000, "800MHz(16bit)"), (10000, "1000MHz(16bit)"), (16300, "1630MHz(16bit)")]:
    target_bytes = struct.pack("<H", target_16)
    positions = []
    start = 0
    while True:
        pos = data.find(target_bytes, start)
        if pos == -1:
            break
        positions.append(pos)
        start = pos + 1
